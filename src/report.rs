//! Rendering. Two audiences: a human skimming a terminal, and a script.

use std::borrow::Cow;
use std::io::IsTerminal;
use std::time::SystemTime;

use serde_json::{Value, json};

use crate::Assessment;
use crate::classify::Verdict;
use crate::inventory::Manager;

struct Style {
    bold: &'static str,
    dim: &'static str,
    reset: &'static str,
}

impl Style {
    fn detect() -> Self {
        // NO_COLOR is a de facto standard; respecting it costs one line.
        let plain = !std::io::stdout().is_terminal() || std::env::var_os("NO_COLOR").is_some();
        if plain {
            Style {
                bold: "",
                dim: "",
                reset: "",
            }
        } else {
            Style {
                bold: "\x1b[1m",
                dim: "\x1b[2m",
                reset: "\x1b[0m",
            }
        }
    }
}

pub fn text(assessments: &[Assessment], now: SystemTime, detailed: bool, only: Option<Verdict>) {
    let s = Style::detect();

    println!(
        "{}shelfware{} — {} packages inspected",
        s.bold,
        s.reset,
        assessments.len()
    );
    println!();

    for verdict in Verdict::ALL {
        let count = assessments.iter().filter(|a| a.verdict == verdict).count();
        println!(
            "  {:<12} {:>4}   {}{}{}",
            verdict.label(),
            count,
            s.dim,
            verdict.headline(),
            s.reset
        );
    }
    println!();

    // Scoped npm names like `@scope/tool` are long; size the column to the
    // data rather than letting every row wrap.
    let name_width = assessments
        .iter()
        .map(|a| a.package.name.len())
        .max()
        .unwrap_or(20)
        .clamp(20, 44);

    for verdict in Verdict::ALL {
        if let Some(wanted) = only {
            if verdict != wanted {
                continue;
            }
        } else if !detailed && !verdict.is_removal_candidate() && verdict != Verdict::Integration {
            // Active and indirect packages are the ones you keep; listing all
            // of them buries the handful you can act on.
            continue;
        }
        let group: Vec<&Assessment> = assessments
            .iter()
            .filter(|a| a.verdict == verdict)
            .collect();
        if group.is_empty() {
            continue;
        }

        println!(
            "{}{}{} — {}",
            s.bold,
            verdict.label().to_uppercase(),
            s.reset,
            verdict.headline()
        );
        for a in group {
            println!(
                "  {:<width$} {:<7} {}{}{}",
                a.package.name,
                a.package.manager.as_str(),
                s.dim,
                evidence(a, now),
                s.reset,
                width = name_width
            );
        }
        println!();
    }

    // Pointless when the reader explicitly asked for another verdict.
    if only.is_some_and(|v| v != Verdict::Unused) {
        return;
    }

    let candidates: Vec<&str> = assessments
        .iter()
        .filter(|a| a.verdict == Verdict::Unused)
        .map(|a| a.package.name.as_str())
        .collect();

    if candidates.is_empty() {
        println!("Nothing looks abandoned. Your shelf is clean.");
    } else {
        // Deliberately not "never ran": a package lands here when nothing has
        // used it *lately*, which is a weaker and more honest claim.
        println!(
            "{}Review these {} first{} — no recent sign of use:",
            s.bold,
            candidates.len(),
            s.reset
        );
        println!("  {}", candidates.join(" "));
        println!();
        println!(
            "{}Check before removing.{} A tool used only inside containers, on \
             another machine, or by a job that has not run this month leaves no \
             trace here.",
            s.dim, s.reset
        );
    }
}

/// A removal script for the user to read, edit, and run themselves.
///
/// Printed rather than executed, on purpose. Some of these verdicts rest on
/// guessed binary names, and every signal here has a documented blind spot —
/// an audit tool has no business uninstalling anything on that basis.
pub fn uninstall_script(assessments: &[Assessment], now: SystemTime, only: Option<Verdict>) {
    let wanted = only.unwrap_or(Verdict::Unused);
    let group: Vec<&Assessment> = assessments.iter().filter(|a| a.verdict == wanted).collect();

    println!("#!/usr/bin/env bash");
    println!("# Generated by shelfware. Review it, delete what you disagree with,");
    println!("# then run it. Nothing here executes on its own.");
    println!("#");
    println!("# Selection: {} — {}", wanted.label(), wanted.headline());
    println!("set -euo pipefail");
    println!();

    if group.is_empty() {
        println!("# Nothing in this category.");
        return;
    }

    for a in group {
        println!("# {} — {}", a.package.name, evidence(a, now));
        if a.package.manager == Manager::Npm {
            println!("#   NOTE: npm binary names are guessed, so \"never typed\" is weak");
            println!("#   evidence here. Confirm this package is genuinely idle first.");
        }
        match uninstall_command(a) {
            Some(cmd) => println!("{cmd}"),
            None => println!(
                "#   no automatic uninstall for manager `{}`",
                a.package.manager.as_str()
            ),
        }
        println!();
    }
}

fn uninstall_command(a: &Assessment) -> Option<String> {
    let name = quote(&a.package.name);
    Some(match a.package.manager {
        Manager::Brew => format!("brew uninstall {name}"),
        Manager::Cargo => format!("cargo uninstall {name}"),
        Manager::Pipx => format!("pipx uninstall {name}"),
        Manager::Uv => format!("uv tool uninstall {name}"),
        Manager::Npm => format!("npm uninstall -g {name}"),
        // `go install` keeps no manifest, so deleting the binary is the
        // uninstall.
        Manager::Go => {
            let path = a.package.binaries.first()?.path.as_ref()?;
            format!("rm -f {}", quote(&path.to_string_lossy()))
        }
    })
}

/// Quote a word for the generated script, but only when it needs it.
///
/// A `GOPATH` with a space in it would otherwise emit an `rm -f` line that
/// takes two arguments instead of one. Left unquoted when it is already safe,
/// because this script exists to be read before it is run.
fn quote(word: &str) -> Cow<'_, str> {
    let safe = |c: char| c.is_ascii_alphanumeric() || "@%+=:,./-_".contains(c);
    if !word.is_empty() && word.chars().all(safe) {
        Cow::Borrowed(word)
    } else {
        Cow::Owned(format!("'{}'", word.replace('\'', r"'\''")))
    }
}

/// One line of "why we said that", so a verdict can be argued with.
fn evidence(a: &Assessment, now: SystemTime) -> String {
    let typed = match a.signals.interactive_hits {
        0 => "never typed".to_string(),
        1 => "typed once".to_string(),
        n => format!("typed {n}×"),
    };
    let run = match a.signals.last_exec {
        Some(t) => format!("last run {}", ago(t, now)),
        None => "never run".to_string(),
    };
    let wired = if a.signals.configured {
        " · in shell config"
    } else {
        ""
    };
    format!("{typed} · {run}{wired}")
}

fn ago(then: SystemTime, now: SystemTime) -> String {
    let Ok(delta) = now.duration_since(then) else {
        return "just now".to_string();
    };
    let days = delta.as_secs() / 86_400;
    match days {
        0 => "today".to_string(),
        1 => "yesterday".to_string(),
        2..=60 => format!("{days}d ago"),
        _ => format!("{}mo ago", days / 30),
    }
}

pub fn json(assessments: &[Assessment], now: SystemTime, only: Option<Verdict>) -> Value {
    let packages: Vec<Value> = assessments
        .iter()
        .filter(|a| only.is_none_or(|wanted| a.verdict == wanted))
        .map(|a| {
            json!({
                "name": a.package.name,
                "manager": a.package.manager.as_str(),
                "verdict": a.verdict.label(),
                "interactive_hits": a.signals.interactive_hits,
                "last_exec_days_ago": a.signals.last_exec.map(|t| {
                    now.duration_since(t).map(|d| d.as_secs() / 86_400).unwrap_or(0)
                }),
                "in_shell_config": a.signals.configured,
                "binaries": a.package.binaries.iter().map(|b| &b.name).collect::<Vec<_>>(),
            })
        })
        .collect();

    json!({ "packages": packages })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::inventory::Binary;
    use std::path::PathBuf;

    fn go_package(path: &str) -> Assessment {
        Assessment {
            package: crate::inventory::Package {
                name: "tool".into(),
                manager: Manager::Go,
                binaries: vec![Binary {
                    name: "tool".into(),
                    path: Some(PathBuf::from(path)),
                }],
            },
            signals: crate::classify::Signals::default(),
            verdict: Verdict::Unused,
        }
    }

    #[test]
    fn ordinary_names_are_left_unquoted() {
        // The script is meant to be read; quoting what needs no quoting is noise.
        assert_eq!(quote("ripgrep"), "ripgrep");
        assert_eq!(quote("@scope/some-tool"), "@scope/some-tool");
        assert_eq!(quote("hashicorp/tap/vault"), "hashicorp/tap/vault");
    }

    #[test]
    fn a_path_with_a_space_stays_one_argument() {
        // Unquoted, this `rm -f` line would take two arguments instead of one.
        let cmd = uninstall_command(&go_package("/Users/ada lovelace/go/bin/tool"))
            .expect("go packages have an uninstall command");
        assert_eq!(cmd, "rm -f '/Users/ada lovelace/go/bin/tool'");
    }

    #[test]
    fn a_quote_in_a_path_cannot_end_the_quoting() {
        assert_eq!(quote("it's"), r"'it'\''s'");
    }

    #[test]
    fn a_go_binary_without_a_path_yields_no_command() {
        let mut assessment = go_package("/tmp/tool");
        assessment.package.binaries[0].path = None;
        assert!(uninstall_command(&assessment).is_none());
    }
}
